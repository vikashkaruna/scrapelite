#!/usr/bin/env node
// deployment/gateway/gen-gateway-conf.mjs — generates the gateway's nginx
// configuration from the repo's routing sources of truth (zero hard-coded
// values, doc 06):
//   - netlify.toml        → 301 redirects (exact-path ones; splat/API rules are
//                           upstream routing, not redirects) + baseline CSP
//   - scripts/site-routes.mjs → PRIVATE_PREFIXES (noindex headers)
// Runs at gateway IMAGE BUILD time; upstream hostnames/ports stay ${VARS}
// resolved by the official nginx image's envsubst (templates/).

import { mkdirSync, writeFileSync } from "node:fs";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..");
const OUT = resolve(argOf("--out", "/out"));

function argOf(k, d) {
  const i = process.argv.indexOf(k);
  return i >= 0 ? process.argv[i + 1] : d;
}

// PRIVATE_PREFIXES from the repo's routing source of truth.
const { PRIVATE_PREFIXES } = await import(
  `file://${process.env.SITE_ROUTES_FILE || resolve(REPO, "scripts", "site-routes.mjs")}`
);

const toml = readFileSync(process.env.NETLIFY_TOML_FILE || resolve(REPO, "netlify.toml"), "utf8");

// ── 301 redirects (exact paths only; splats/force-200 belong to upstreams) ────
const redirects = [];
for (const block of toml.split(/\[\[redirects\]\]/).slice(1)) {
  const pick = (key) => {
    // values appear quoted (from/to) or bare integers (status)
    const m = new RegExp(`^\\s*${key}\\s*=\\s*(?:"([^"]*)"|([^\\s#]+))`, "m").exec(block);
    return m ? (m[1] ?? m[2] ?? "").trim() : "";
  };
  const from = pick("from");
  const to = pick("to");
  const status = Number(pick("status") || "301");
  if (!from || !to) continue;
  if (status !== 301) continue; // 200-rewrites are handled by upstreams/gateway routing
  if (/[:*]/.test(from)) continue; // splat rules are not exact-location material
  redirects.push({ from, to });
}

// ── baseline headers (mirrors the netlify.toml /* block) ──────────────────────
const cspMatch = /Content-Security-Policy\s*=\s*"([^"]+)"/.exec(toml);
if (!cspMatch) {
  console.error("✗ gen-gateway-conf: no Content-Security-Policy found in netlify.toml");
  process.exit(1);
}
const CSP = cspMatch[1];

const baseline = `# GENERATED by deployment/gateway/gen-gateway-conf.mjs (netlify.toml /* block) — do not edit.
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "DENY" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
add_header Content-Security-Policy "${CSP}" always;
`;

// ── server template (envsubst resolves ${LOCAL_GATEWAY_PORT} + upstreams) ─────
const adminNoindex = PRIVATE_PREFIXES.includes("/admin")
  ? `      add_header X-Robots-Tag "noindex, nofollow" always;\n      add_header Cache-Control "no-store" always;\n`
  : "";

const template = `# GENERATED by deployment/gateway/gen-gateway-conf.mjs — do not edit.
# Edge parity with netlify.toml: 301s, baseline headers, upstream routing.
# Upstreams resolve at REQUEST time via docker DNS (127.0.0.11) so the gateway
# starts even while a sibling is restarting (nginx would otherwise exit on an
# unresolvable static proxy_pass).
server {
  listen \${LOCAL_GATEWAY_PORT};
  server_name _;
  client_max_body_size 64m;

  resolver 127.0.0.11 valid=10s ipv6=off;

  include /etc/nginx/conf.d/baseline.inc;

  location = /healthz { access_log off; return 200 "ok\\n"; }

  # tracker/config layer — its own deployable (doc 05 FR-0)
  location = /runtime-config.js { set $up http://\${TRACKERS_UPSTREAM}; proxy_pass $up; }
  location = /analytics.js      { set $up http://\${TRACKERS_UPSTREAM}; proxy_pass $up; }

  # admin surface — separately deployable/restrictable
  location /admin {
    set $up http://\${ADMIN_UPSTREAM};
    proxy_pass $up;
${adminNoindex}    include /etc/nginx/conf.d/baseline.inc;
  }

  location /api/ {
    set $up http://\${API_UPSTREAM};
    proxy_pass $up;
    proxy_read_timeout 300s;
    proxy_send_timeout 300s;
    include /etc/nginx/conf.d/baseline.inc;
  }
  location /auth/ { set $up http://\${AUTH_UPSTREAM}; rewrite ^/auth/v1(/.*)$ $1 break; rewrite ^/auth/v1$ / break; proxy_pass $up; include /etc/nginx/conf.d/baseline.inc; }
  location /rest/ { set $up http://\${REST_UPSTREAM}; rewrite ^/rest/v1(/.*)$ $1 break; rewrite ^/rest/v1$ / break; proxy_pass $up; include /etc/nginx/conf.d/baseline.inc; }

${redirects.map((r) => `  location = ${r.from} { return 301 ${r.to}; }`).join("\n")}

  # everything else: the web surface (static + prerendered + SPA fallback)
  location / { set $up http://\${WEB_UPSTREAM}; proxy_pass $up; include /etc/nginx/conf.d/baseline.inc; }
}
`;

mkdirSync(OUT, { recursive: true });
mkdirSync(resolve(OUT, "conf.d"), { recursive: true });
mkdirSync(resolve(OUT, "templates"), { recursive: true });
writeFileSync(resolve(OUT, "conf.d", "baseline.inc"), baseline);
writeFileSync(resolve(OUT, "templates", "datiq.conf.template"), template);
writeFileSync(
  resolve(OUT, "nginx.conf"),
  `# GENERATED by deployment/gateway/gen-gateway-conf.mjs — do not edit.
worker_processes auto;
error_log /var/log/nginx/error.log warn;
events { worker_connections 1024; }
http {
  include /etc/nginx/mime.types;
  default_type application/octet-stream;
  sendfile on;
  keepalive_timeout 75s;
  client_max_body_size 64m;
  proxy_http_version 1.1;
  access_log /var/log/nginx/access.log;
  include /etc/nginx/conf.d/*.conf;
}
`,
);
console.log(
  `✓ gen-gateway-conf: ${redirects.length} exact 301s, ${PRIVATE_PREFIXES.length} private prefixes, CSP ok → ${OUT}`,
);
