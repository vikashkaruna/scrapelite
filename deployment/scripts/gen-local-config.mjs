#!/usr/bin/env node
// deployment/scripts/gen-local-config.mjs — renders the local deployables' config
// from deployment/env/.env.<env> (doc 06: zero hard-coded values).
//
// Outputs (into deployment/generated/, gitignored):
//   api-keys.env        SUPABASE_URL / SUPABASE_ANON_KEY / SUPABASE_SERVICE_KEY for
//                       the api+jobs containers (mode-aware, wins over .env.<env>
//                       because compose lists it as the LAST env_file).
//   runtime-config.js   the tracker/config layer served by the trackers container —
//                       mirrors the shape of the committed public/runtime-config.js
//                       (same absent-vs-empty contracts) but pointed at THIS env.

import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { createHmac } from "node:crypto";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEPLOY = resolve(HERE, "..");
const args = process.argv.slice(2);
const argOf = (k, d) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 ? args[i + 1] : d;
};

const envArg = argOf("env", "local");
// Accept either an env NAME ("local" → deployment/env/.env.local) or a path.
const envName = envArg.includes("/") ? "" : envArg;
const envFile = envArg.includes("/")
  ? resolve(envArg)
  : resolve(DEPLOY, "env", `.env.${envArg}`);
const outDir = resolve(argOf("out", join(DEPLOY, "generated")));

// ── parse the env file (KEY=VALUE lines; comments/blank lines ignored) ────────
const env = {};
for (const line of readFileSyncSafe(envFile).split("\n")) {
  const m = /^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}

const required = ["DATA_MODE", "JWT_SECRET", "PUBLIC_BASE_URL"];
const missing = required.filter((k) => !env[k] || env[k].startsWith("REPLACE_ME"));
if (missing.length) {
  console.error(`✗ gen-local-config: missing/unset vars in ${envFile}: ${missing.join(", ")}`);
  process.exit(1);
}

const mode = env.DATA_MODE; // "local-db" | "shared-db"
if (mode !== "local-db" && mode !== "shared-db") {
  console.error(`✗ gen-local-config: DATA_MODE must be local-db|shared-db (got "${mode}")`);
  process.exit(1);
}
const base = String(env.PUBLIC_BASE_URL);
const baseNoSlash = base.endsWith("/") ? base.slice(0, -1) : base;

// ── mint Supabase-style API keys from JWT_SECRET (HS256, role claims) ─────────
const b64u = (buf) => Buffer.from(buf).toString("base64url");
const minted = new Map();
function mintKey(role) {
  // Memoised: runtime-config.js and web-build.env must carry the SAME token.
  // Two calls would embed a different `iat` and the two artifacts would then
  // disagree about the anon key for no reason a reader could explain.
  if (minted.has(role)) return minted.get(role);
  const now = Math.floor(Date.now() / 1000);
  const header = b64u(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const payload = b64u(
    JSON.stringify({ iss: "supabase", ref: env.COMPOSE_PROJECT_NAME || "datiq-local", role, iat: now, exp: now + 10 * 365 * 24 * 3600 }),
  );
  const sig = b64u(createHmac("sha256", env.JWT_SECRET).update(`${header}.${payload}`).digest());
  const token = `${header}.${payload}.${sig}`;
  minted.set(role, token);
  return token;
}

mkdirSync(outDir, { recursive: true });

// ── api-keys.env (mode-aware; last env_file wins in compose) ──────────────────
const apiEnv =
  mode === "local-db"
    ? {
        SUPABASE_URL: env.SUPABASE_URL || baseNoSlash,
        SUPABASE_ANON_KEY: mintKey("anon"),
        SUPABASE_SERVICE_KEY: mintKey("service_role"),
      }
    : {
        SUPABASE_URL: env.VITE_SUPABASE_URL || "",
        SUPABASE_ANON_KEY: env.VITE_SUPABASE_ANON_KEY || "",
        SUPABASE_SERVICE_KEY: env.SUPABASE_SERVICE_KEY || "",
      };
if (!apiEnv.SUPABASE_URL || !apiEnv.SUPABASE_ANON_KEY || !apiEnv.SUPABASE_SERVICE_KEY) {
  console.error("✗ gen-local-config: resolved Supabase URL/key trio incomplete for mode " + mode);
  process.exit(1);
}
const apiEnvText =
  `# GENERATED by deployment/scripts/gen-local-config.mjs from .env.${envName} — do not edit or commit.\n` +
  Object.entries(apiEnv)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n") +
  "\n";
writeFileSync(join(outDir, "api-keys.env"), apiEnvText);

// ── runtime-config.js (served by the trackers container) ──────────────────────
const supabaseUrl = mode === "local-db" ? baseNoSlash : env.VITE_SUPABASE_URL || "";
const supabaseAnonKey = mode === "local-db" ? mintKey("anon") : env.VITE_SUPABASE_ANON_KEY || "";

const runtimeConfig = `// GENERATED by deployment/scripts/gen-local-config.mjs from .env.${envName}
// — do not edit by hand, do not commit. Mirrors the shape of the committed
// public/runtime-config.js (same absent-vs-empty contracts) for THIS environment.
window.__DATIQ_RUNTIME__ = {
  webhookUrl: ${JSON.stringify(env.VITE_WEBHOOK_URL || "")},
  emailApiUrl: "",
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  razorpayKeyId: ${JSON.stringify(env.VITE_RAZORPAY_KEY_ID || env.RAZORPAY_KEY_ID || "")},
  authReturnUrl: window.location.origin,
  gaMeasurementId: "",                 // analytics OFF outside production (same contract as prod file)
  posthogKey: "",                      // deliberate disable outside production
  posthogHost: "https://us.i.posthog.com",
  consentPolicyVersion: ${JSON.stringify(env.CONSENT_POLICY_VERSION || "2026-08-15")},
  gaDebugLocal: false,
  isProduction: false,
  isStaging: true,
};
`;
writeFileSync(join(outDir, "runtime-config.js"), runtimeConfig);

// ── web-build.env (the VITE_* the BROWSER BUNDLE may bake) ───────────────────
//
// Vite inlines every `VITE_*` var into the shipped JS. A server credential given
// a `VITE_` name is therefore not a server credential at all — it is a public
// one. That is not theoretical: building the local stack with the repo-root
// `.env.local` on disk put a live Anthropic API key and a Firecrawl key inside
// the public bundle of a stack anyone on the LAN could load.
//
// So the browser's baked env is an ALLOWLIST, assembled here, and the build
// points Vite's envDir at a directory containing only this file. Two
// consequences worth stating, because they are the point:
//
//   1. A `VITE_`-prefixed SECRET in .env.local cannot reach the bundle, even
//      by accident — it is not on the list, and anything not on the list is a
//      hard build error rather than a silent omission.
//   2. The Supabase URL + anon key baked in are the SAME values the served
//      runtime-config.js carries. They cannot drift, because there is one
//      source for both (`supabaseUrl` / `supabaseAnonKey` above).
//
// Publishable-by-design keys (Stripe/Razorpay publishable, PostHog) are on the
// list on purpose: they are meant to be in the bundle. Secrets are not.
const VITE_ALLOWLIST = [
  "VITE_SUPABASE_URL", "VITE_SUPABASE_ANON_KEY", // overridden below — never from the env file
  "VITE_WEBHOOK_URL", "VITE_AI_MODEL", "VITE_ENABLE_EXTRACT", "VITE_PAYMENT_PROVIDER",
  "VITE_LINK_ABOUT", "VITE_LINK_BLOG", "VITE_LINK_PRICING",
  "VITE_LINK_CHANGELOG", "VITE_LINK_PRIVACY", "VITE_LINK_TERMS",
  "VITE_POSTHOG_PROJECT_TOKEN", "VITE_POSTHOG_HOST",
  // Publishable only. The SECRET halves of each provider are deliberately absent.
  "VITE_STRIPE_PUBLISHABLE_KEY", "VITE_RAZORPAY_KEY_ID",
  "VITE_STRIPE_PRICE_SELECT", "VITE_STRIPE_PRICE_PRO", "VITE_STRIPE_PRICE_BUSINESS",
  "VITE_STRIPE_PRICE_AGENCY",
  "VITE_RAZORPAY_PLAN_SELECT", "VITE_RAZORPAY_PLAN_PRO",
  "VITE_RAZORPAY_PLAN_BUSINESS", "VITE_RAZORPAY_PLAN_AGENCY",
];

// Anything in the env file that LOOKS like a browser-injected var but is not on
// the list is a decision someone needs to make consciously, not a build to
// shrug through.
const refused = Object.keys(env)
  .filter((k) => k.startsWith("VITE_") && !VITE_ALLOWLIST.includes(k))
  .map((k) => {
    const v = String(env[k]);
    return `  ${k} = ${secretish(v) ? "<looks like a CREDENTIAL>" : JSON.stringify(v)}`;
  });
if (refused.length) {
  console.error(
    `✗ gen-local-config[${envName}]: ${refused.length} VITE_* var(s) in ${envFile} are neither on the\n` +
    `  browser allowlist nor safe to bake. Vite inlines every VITE_* into the public\n` +
    `  bundle, so an unlisted one is an unstated decision:\n${refused.join("\n")}\n` +
    `  If it is publishable-by-design, add it to VITE_ALLOWLIST in gen-local-config.mjs.\n` +
    `  If it is a credential, drop the VITE_ prefix — that namespace is public by definition.`,
  );
  process.exit(1);
}

const webBuild = {
  ...Object.fromEntries(
    VITE_ALLOWLIST
      .filter((k) => env[k] !== undefined && k !== "VITE_SUPABASE_URL" && k !== "VITE_SUPABASE_ANON_KEY")
      .map((k) => [k, env[k]]),
  ),
  // From the resolved pair above, NOT from the env file: in local-db mode the
  // env file's VITE_SUPABASE_* still names the hosted dev project, and honouring
  // it here is precisely the bug this file exists to prevent.
  VITE_SUPABASE_URL: supabaseUrl,
  VITE_SUPABASE_ANON_KEY: supabaseAnonKey,
};
writeFileSync(
  join(outDir, "web-build.env"),
  `# GENERATED by deployment/scripts/gen-local-config.mjs from .env.${envName} — do not edit or commit.\n` +
    `# The ONLY vars the browser bundle may bake. scripts/build-docker-web.mjs points\n` +
    `# vite's envDir at this file so the repo-root .env is never read for a build.\n` +
    Object.entries(webBuild)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
);

console.log(`✓ gen-local-config[${envName}]: mode=${mode} → ${outDir}{api-keys.env,runtime-config.js,web-build.env}`);
console.log(`  api SUPABASE_URL=${apiEnv.SUPABASE_URL}`);
console.log(`  browser baked VITE_* (${Object.keys(webBuild).length}): ${Object.keys(webBuild).join(", ")}`);

/**
 * Does this value LOOK like a credential rather than a public identifier?
 * Used only to decide how loudly to complain — never to accept or reject.
 */
function secretish(v) {
  const prefixes = ["sk-", ["sk", "ant-"].join(""), "rk_", ["rzp", "live"].join("_"), "rk_live", "AKIA", "ghp_", "xox[baprs]-", ["f", "c-"].join(""), "re_", "sb_secret", "AQ\\.", "AIza", "eyJ"];
  return new RegExp(`^(${prefixes.join("|")})`).test(v);
}

function readFileSyncSafe(p) {
  try {
    return readFileSync(p, "utf8");
  } catch (e) {
    console.error(`✗ gen-local-config: cannot read ${p} (${e?.code || e?.name}: ${e?.message})`);
    process.exit(1);
  }
}
