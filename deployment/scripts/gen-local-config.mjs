#!/usr/bin/env node
// deployment/scripts/gen-local-config.mjs — renders the local deployables' config
// from deployment/env/.env.<env> (doc 06: zero hard-coded values).
//
// Outputs (into deployment/generated/, gitignored):
//   api-keys.env        SUPABASE_URL / SUPABASE_ANON_KEY / SUPABASE_SERVICE_KEY for
//                       the api+jobs containers (mode-aware, wins over .env.<env>
//                       because compose lists it as the LAST env_file).
//   runtime-config.js   the tracker/config layer served by the trackers container —
//                       mirrors the shape of the committed public/runtime-config.js
//                       (same absent-vs-empty contracts) but pointed at THIS env.

import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { createHmac } from "node:crypto";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEPLOY = resolve(HERE, "..");
const args = process.argv.slice(2);
const argOf = (k, d) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 ? args[i + 1] : d;
};

const envArg = argOf("env", "local");
// Accept either an env NAME ("local" → deployment/env/.env.local) or a path.
const envName = envArg.includes("/") ? "" : envArg;
const envFile = envArg.includes("/")
  ? resolve(envArg)
  : resolve(DEPLOY, "env", `.env.${envArg}`);
const outDir = resolve(argOf("out", join(DEPLOY, "generated")));

// ── parse the env file (KEY=VALUE lines; comments/blank lines ignored) ────────
const env = {};
for (const line of readFileSyncSafe(envFile).split("\n")) {
  const m = /^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}

const required = ["DATA_MODE", "JWT_SECRET", "PUBLIC_BASE_URL"];
const missing = required.filter((k) => !env[k] || env[k].startsWith("REPLACE_ME"));
if (missing.length) {
  console.error(`✗ gen-local-config: missing/unset vars in ${envFile}: ${missing.join(", ")}`);
  process.exit(1);
}

const mode = env.DATA_MODE; // "local-db" | "shared-db"
if (mode !== "local-db" && mode !== "shared-db") {
  console.error(`✗ gen-local-config: DATA_MODE must be local-db|shared-db (got "${mode}")`);
  process.exit(1);
}
const base = String(env.PUBLIC_BASE_URL);
const baseNoSlash = base.endsWith("/") ? base.slice(0, -1) : base;

// ── mint Supabase-style API keys from JWT_SECRET (HS256, role claims) ─────────
const b64u = (buf) => Buffer.from(buf).toString("base64url");
function mintKey(role) {
  const now = Math.floor(Date.now() / 1000);
  const header = b64u(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const payload = b64u(
    JSON.stringify({ iss: "supabase", ref: env.COMPOSE_PROJECT_NAME || "datiq-local", role, iat: now, exp: now + 10 * 365 * 24 * 3600 }),
  );
  const sig = b64u(createHmac("sha256", env.JWT_SECRET).update(`${header}.${payload}`).digest());
  return `${header}.${payload}.${sig}`;
}

mkdirSync(outDir, { recursive: true });

// ── api-keys.env (mode-aware; last env_file wins in compose) ──────────────────
const apiEnv =
  mode === "local-db"
    ? {
        SUPABASE_URL: env.SUPABASE_URL || baseNoSlash,
        SUPABASE_ANON_KEY: mintKey("anon"),
        SUPABASE_SERVICE_KEY: mintKey("service_role"),
      }
    : {
        SUPABASE_URL: env.VITE_SUPABASE_URL || "",
        SUPABASE_ANON_KEY: env.VITE_SUPABASE_ANON_KEY || "",
        SUPABASE_SERVICE_KEY: env.SUPABASE_SERVICE_KEY || "",
      };
if (!apiEnv.SUPABASE_URL || !apiEnv.SUPABASE_ANON_KEY || !apiEnv.SUPABASE_SERVICE_KEY) {
  console.error("✗ gen-local-config: resolved Supabase URL/key trio incomplete for mode " + mode);
  process.exit(1);
}
const apiEnvText =
  `# GENERATED by deployment/scripts/gen-local-config.mjs from .env.${envName} — do not edit or commit.\n` +
  Object.entries(apiEnv)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n") +
  "\n";
writeFileSync(join(outDir, "api-keys.env"), apiEnvText);

// ── runtime-config.js (served by the trackers container) ──────────────────────
const runtimeConfig = `// GENERATED by deployment/scripts/gen-local-config.mjs from .env.${envName}
// — do not edit by hand, do not commit. Mirrors the shape of the committed
// public/runtime-config.js (same absent-vs-empty contracts) for THIS environment.
window.__DATIQ_RUNTIME__ = {
  webhookUrl: ${JSON.stringify(env.VITE_WEBHOOK_URL || "")},
  emailApiUrl: "",
  supabaseUrl: ${JSON.stringify(mode === "local-db" ? baseNoSlash : env.VITE_SUPABASE_URL || "")},
  supabaseAnonKey: ${JSON.stringify(mode === "local-db" ? mintKey("anon") : env.VITE_SUPABASE_ANON_KEY || "")},
  authReturnUrl: window.location.origin,
  gaMeasurementId: "",                 // analytics OFF outside production (same contract as prod file)
  posthogKey: "",                      // deliberate disable outside production
  posthogHost: "https://us.i.posthog.com",
  consentPolicyVersion: ${JSON.stringify(env.CONSENT_POLICY_VERSION || "2026-08-15")},
  gaDebugLocal: false,
  isProduction: false,
  isStaging: true,
};
`;
writeFileSync(join(outDir, "runtime-config.js"), runtimeConfig);

console.log(`✓ gen-local-config[${envName}]: mode=${mode} → ${outDir}{api-keys.env,runtime-config.js}`);
console.log(`  api SUPABASE_URL=${apiEnv.SUPABASE_URL}`);

function readFileSyncSafe(p) {
  try {
    return readFileSync(p, "utf8");
  } catch (e) {
    console.error(`✗ gen-local-config: cannot read ${p} (${e?.code || e?.name}: ${e?.message})`);
    process.exit(1);
  }
}
