/** Convenience: every public URL, in sitemap order. */
export function allPublicRoutes() {
  return [...REACT_OWNED, ...STATIC_OWNED, HELP_INDEX];
}

/**
 * The React-owned routes that actually get a generated file. Excludes `/`
 * for the reason documented on its entry above.
 */
export function prerenderableRoutes() {
  return REACT_OWNED.filter((r) => r.prerender !== false);
}

/**
 * public/<dir>/index.html for a prerenderable route. Throws on "/" rather than
 * returning "index.html", because that path would clobber Vite's entry point
 * and a silent return here is how that bug would reach a build.
 */
export function generatedFileFor(routePath) {
  if (routePath === "/") {
    throw new Error(
      "generatedFileFor('/') — the homepage is not prerendered; " +
      "public/index.html would overwrite Vite's build entry. See site-routes.mjs.",
    );
  }
  return `${routePath.replace(/^\/+/, "").replace(/\/+$/, "")}/index.html`;
}
