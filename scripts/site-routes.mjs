// scripts/site-routes.mjs — the single source of truth for what URLs this site
// has and WHO OWNS each one.
//
// Three consumers read this file and must never disagree:
//   * scripts/prerender.mjs        — renders every REACT_OWNED route to HTML
//   * scripts/build-sitemap.mjs    — lists REACT_OWNED + STATIC_OWNED
//   * scripts/page-ownership.test.mjs — asserts reality matches this list
//
// ── Why ownership is explicit ────────────────────────────────────────────
// This site used to serve TWENTY URLs from two different documents: a
// hand-written file under public/ for cold hits and crawlers, and a React page
// for in-app navigation. Same URL, two sources, maintained separately — and
// they had already drifted (llms.txt advertised prices the pricing page had
// not used for months). Every URL now has exactly one owner.
//
//   REACT_OWNED   the page is authored in JSX. Its static HTML is GENERATED by
//                 scripts/prerender.mjs and committed. Never hand-edit the
//                 generated file; edit the component and re-run the script.
//
//   STATIC_OWNED  the page is authored as hand-written HTML under public/.
//                 There is deliberately NO React route for it, and links to it
//                 are plain <a href> / external:true so the browser does a full
//                 load rather than falling through to the SPA's NotFound.
//
//   PRIVATE       the signed-in application. Never indexed, never prerendered,
//                 and must never keep index.html's root canonical — that is
//                 what got /privacy, /terms and /vs/battlecard dropped from
//                 Google's index as duplicates of the homepage.

