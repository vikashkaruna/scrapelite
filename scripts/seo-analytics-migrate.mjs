// scripts/seo-analytics-migrate.mjs — idempotent sweep over every static HTML
// page, ensuring two things that are easy to forget on a hand-written file:
//
//   1. the shared Google tag loader (/runtime-config.js + /analytics.js),
//      immediately after <head> — the placement Google's own instructions ask
//      for, and the placement the Consent Mode default depends on;
//   2. a self-referencing <link rel="canonical">.
//
//   node scripts/seo-analytics-migrate.mjs           apply
//   node scripts/seo-analytics-migrate.mjs --check   exit 1 if anything missing
//
// Modelled on scripts/og-image-migrate.mjs. Safe to run repeatedly.
//
// ── Why canonicals matter here specifically ──────────────────────────────
// Twenty-five static files shipped with NO canonical at all — every page under
// public/help/, plus dmca.html and four /vs/ pages. A page with no canonical
// is not broken, but it gives Google nothing to consolidate on, and this site
// serves several near-duplicate URLs (directory and .html forms of the same
// comparison). Silence there is how /vs/firecrawl.html and
// /vs/firecrawl/index.html — byte-identical — both stayed live and competed.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const PUBLIC = join(ROOT, "public");
const CHECK = process.argv.includes("--check");
const ORIGIN = "https://datiq.app";

const LOADER = [
  "<script src=\"/runtime-config.js\"></script>",
  "<script src=\"/analytics.js\"></script>",
].join("\n");

/** Files that are generated by the prerenderer — it emits the tags itself. */
function isPrerendered(html) {
  return html.includes("GENERATED by scripts/prerender.mjs");
}

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, acc);
    else if (name.endsWith(".html")) acc.push(p);
  }
  return acc;
}

/** public/vs/apify/index.html → /vs/apify ; public/dmca.html → /dmca */
export function urlForFile(relPath) {
  let u = "/" + relPath.replace(/\\/g, "/");
  u = u.replace(/\/index\.html$/, "");
  // help/ pages keep their .html — they are linked and indexed that way.
  if (!u.startsWith("/help/")) u = u.replace(/\.html$/, "");
  return u === "" ? "/" : u;
}

export function needsLoader(html) {
  return !html.includes('src="/analytics.js"');
}

export function needsCanonical(html) {
  return !/<link[^>]+rel=["']canonical["']/i.test(html);
}

export function addLoader(html) {
  // Immediately after <head>, before anything else can run.
  return html.replace(/<head([^>]*)>/i, (m) => `${m}\n${LOADER}`);
}

export function addCanonical(html, url) {
  const tag = `<link rel="canonical" href="${ORIGIN}${url}">`;
  // Prefer to sit next to the description, where the other SEO tags live.
  if (/<meta[^>]+name=["']description["'][^>]*>/i.test(html)) {
    return html.replace(/(<meta[^>]+name=["']description["'][^>]*>)/i, `$1\n${tag}`);
  }
  return html.replace(/<head([^>]*)>/i, (m) => `${m}\n${tag}`);
}

const files = existsSync(PUBLIC) ? walk(PUBLIC) : [];
const missing = [];
let touched = 0;

for (const file of files) {
  const rel = relative(PUBLIC, file);
  const url = urlForFile(rel);
  let html = readFileSync(file, "utf8");
  const original = html;

  if (isPrerendered(html)) continue;

  if (needsLoader(html)) {
    if (CHECK) missing.push(`${rel} — no /analytics.js`);
    else html = addLoader(html);
  }
  if (needsCanonical(html)) {
    if (CHECK) missing.push(`${rel} — no canonical`);
    else html = addCanonical(html, url);
  }

  if (!CHECK && html !== original) {
    writeFileSync(file, html, "utf8");
    touched++;
    console.log(`  ✓ ${rel}`);
  }
}

if (CHECK) {
  console.log(`[seo-analytics] ${files.length} static page(s) checked · ${missing.length} problem(s)`);
  missing.forEach((m) => console.log(`  ✗ ${m}`));
  process.exit(missing.length ? 1 : 0);
} else {
  console.log(`[seo-analytics] ${files.length} static page(s) · ${touched} updated`);
}
